"""Generate circuits/lib/tcl/poseidon_constants.circom (Apache-2.0).

Round constants C are regenerated *in-house* with the Grain LFSR procedure from the
Poseidon paper (field=prime, x^5 S-box, n=254, t, R_F=8, R_P) and asserted equal to the
pinned table in src/tcl/crypto/poseidon_bn254_t2_t5.json. MDS matrices M are taken from
that pinned table (public parameters; regenerating M with the reference security
checks is not implemented yet, see docs/DECISIONS.md D-OFF-4).

  python scripts/gen_poseidon_constants.py          # write the .circom
  python scripts/gen_poseidon_constants.py --check  # fail if the committed file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLE = ROOT / "src/tcl/crypto/poseidon_bn254_t2_t5.json"
OUT = ROOT / "circuits/lib/tcl/poseidon_constants.circom"
P = 21888242871839275222246405745257275088548364400416034343698204186575808495617
R_F = 8
R_P = [56, 57, 56, 60]


def _bits(v: int, w: int) -> list[int]:
    return [int(b) for b in format(v, f"0{w}b")]


def grain_round_constants(t: int, rf: int, rp: int, n: int = 254) -> list[int]:
    s = [0, 1] + [0] * 4 + _bits(n, 12) + _bits(t, 12) + _bits(rf, 10) + _bits(rp, 10) + [1] * 30

    def step() -> int:
        b = s[62] ^ s[51] ^ s[38] ^ s[23] ^ s[13] ^ s[0]
        s.pop(0)
        s.append(b)
        return b

    for _ in range(160):
        step()

    def bit() -> int:
        while True:
            a, b = step(), step()
            if a == 1:
                return b

    out = []
    while len(out) < (rf + rp) * t:
        v = 0
        for _ in range(n):
            v = (v << 1) | bit()
        if v < P:
            out.append(v)
    return out


def render() -> str:
    raw = json.loads(TABLE.read_text())
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// GENERATED by scripts/gen_poseidon_constants.py -- do not edit.",
        "// C: Grain-LFSR regenerated in-house; M: pinned public parameters.",
        "pragma circom 2.1.6;",
        "",
    ]
    cs, ms = [], []
    for i, rp in enumerate(R_P):
        t = i + 2
        c = grain_round_constants(t, R_F, rp)
        if c != [int(x, 16) for x in raw["C"][i]]:
            raise SystemExit(f"Grain round constants for t={t} differ from pinned table")
        cs.append((t, c))
        ms.append((t, [[int(x, 16) for x in r] for r in raw["M"][i]]))
    lines.append("function TCL_POSEIDON_C(t) {")
    for t, c in cs:
        lines.append(f"    if (t == {t}) {{ return [{', '.join(str(x) for x in c)}]; }}")
    lines += ["    assert(0);", "    return [0];", "}", "", "function TCL_POSEIDON_M(t) {"]
    for t, m in ms:
        rows = ", ".join("[" + ", ".join(str(x) for x in r) + "]" for r in m)
        lines.append(f"    if (t == {t}) {{ return [{rows}]; }}")
    lines += ["    assert(0);", "    return [[0]];", "}", ""]
    return "\n".join(lines)


def main() -> int:
    txt = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != txt:
            print(f"{OUT} is stale; run scripts/gen_poseidon_constants.py", file=sys.stderr)
            return 1
        print("poseidon constants OK")
        return 0
    OUT.write_text(txt)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
